def get_judgment(hex_no: int) -> str:
    """Get the hexagram judgment (卦辭) for a given hexagram number."""
    data = HEXAGRAM_DATA.get(hex_no)
    if not data:
        return "待查"
    return data["judgment"]


def get_line_text(hex_no: int, line_idx: int) -> str:
    """Get the line text (爻辭) for a specific line of a hexagram.
    
    Args:
        hex_no: Hexagram number (1-64)
        line_idx: Line index (0=bottom/初, 5=top/上)
    Returns:
        Compact interpretation string
    """
    data = HEXAGRAM_DATA.get(hex_no)
    if not data:
        position = LINE_POSITION.get(line_idx, {}).get("name", "?")
        return f"{position}爻：參考卦象，審時度勢。"
    lines = data.get("lines", [])
    if 0 <= line_idx < len(lines):
        # Extract the interpretation part after the traditional text
        text = lines[line_idx]
        # Remove the traditional format (e.g. "初九：潛龍勿用。") to get just the modern interpretation
        # Keep the full text as it's already compact
        return text
    position = LINE_POSITION.get(line_idx, {}).get("name", "?")
    return f"{position}爻：參考卦象，謹慎行事。"


def resolve_line_by_moving(hex_no: int, moving_indexes: list[int]) -> str:
    """Resolve which interpretation to show using the traditional Zhu Xi rules.
    
    Rules:
      0 變爻 (靜卦) → 本卦卦辭
      1 變爻 → 該爻爻辭（本卦）
      2 變爻 → 本卦兩爻爻辭（以上爻為主）
      3 變爻 → 本卦與變卦卦辭
      4 變爻 → 變卦兩個不變爻（以下爻為主）
      5 變爻 → 變卦不變爻爻辭
      6 變爻 → 變卦卦辭（乾坤用九/用六）
    
    Args:
        hex_no: Original hexagram number
        moving_indexes: List of moving line indices (0-based, bottom=0)
    Returns:
        Tuple of (interpretation text, rule_explanation)
    """
    count = len(moving_indexes)
    
    if count == 0:
        # 靜卦：看本卦卦辭
        text = get_judgment(hex_no)
        return text, "靜卦，卦辭"
    
    elif count == 1:
        # 一爻變：看該爻爻辭
        idx = moving_indexes[0]
        text = get_line_text(hex_no, idx)
        return text, f"一爻變，{LINE_POSITION[idx]['name']}爻爻辭"
    
    elif count == 2:
        # 二爻變：兩爻並看，以上爻為主。
        lower_idx, upper_idx = sorted(moving_indexes)
        text = (
            f"主：{get_line_text(hex_no, upper_idx)}；"
            f"參：{get_line_text(hex_no, lower_idx)}"
        )
        return text, f"二爻變，兩爻並看，以上{LINE_POSITION[upper_idx]['name']}爻為主"
    
    elif count == 3:
        # 三爻變：本卦與變卦卦辭並看，交由呼叫端補變卦。
        # The caller needs to compute the changed hexagram number
        return "三爻變，本卦與變卦卦辭並看", "三爻變，本卦與變卦卦辭"
    
    elif count == 4:
        # 四爻變：變卦兩個不變爻並看，以下爻為主。
        return "四爻變，看變卦兩個不變爻，以下爻為主", "四爻變，兩個不變爻"
    
    elif count == 5:
        # 五爻變：看變卦不變爻
        return "五爻變，看變卦不變爻", "五爻變，不變爻"
    
    elif count == 6:
        # 六爻全變：看變卦卦辭
        # Special case for 乾 (1) and 坤 (2)
        if hex_no == 1:
            return "群龍無首，吉。用九：見群龍無首，天則也。", "六爻全變，用九"
        if hex_no == 2:
            return "利永貞。用六：利永貞，以終也。", "六爻全變，用六"
        return "六爻全變，看變卦卦辭", "六爻全變，變卦卦辭"
    
    return "參考卦象，謹慎行事。", "通用"
